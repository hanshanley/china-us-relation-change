#!/usr/bin/env python3
"""Keep GitHub's essay figure collection aligned with the validated public edition."""

import argparse
import hashlib
import json
import shutil
from pathlib import Path, PurePosixPath


ROOT = Path(__file__).resolve().parents[1]


def sync_published_figures(root, site):
    root, site = root.resolve(), site.resolve()
    target = root / "outputs/figures"
    if not target.resolve().is_relative_to(root):
        raise ValueError("Figure destination must remain inside the repository")
    manifest = json.loads((site / "publication-manifest.json").read_text())
    approved = {}
    for name, digest in manifest["files"].items():
        path = PurePosixPath(name)
        if not name.startswith("figures/") or path.suffix.lower() not in {".png", ".svg"}:
            continue
        if path.is_absolute() or ".." in path.parts or any(c in name for c in "*?[]\n\r\0"):
            raise ValueError("Invalid published figure path")
        source = site / path
        relative = Path(*path.parts[1:])
        destination = target / relative
        if not source.resolve().is_relative_to(site) or not destination.resolve().is_relative_to(target.resolve()):
            raise ValueError("Published figure path escapes its directory")
        if hashlib.sha256(source.read_bytes()).hexdigest() != digest:
            raise ValueError("Published figure checksum mismatch: " + name)
        approved[relative] = source
    if not approved:
        raise ValueError("No published figures declared; refusing to empty the collection")
    removed = []
    target.mkdir(parents=True, exist_ok=True)
    for path in sorted(target.rglob("*")):
        if path.is_file() and path.suffix.lower() in {".png", ".svg"}:
            relative = path.relative_to(target)
            if relative not in approved:
                path.unlink()
                removed.append(relative.as_posix())
    for relative, source in approved.items():
        destination = target / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        if not destination.is_file() or destination.read_bytes() != source.read_bytes():
            shutil.copyfile(source, destination)
    allowed = sorted(path.as_posix() for path in approved)
    (target / ".gitignore").write_text(
        "# Generated by scripts/sync_published_figures.py; only publication-used charts belong in Git.\n"
        "*.png\n*.svg\n" + "".join(f"!/{name}\n" for name in allowed), encoding="utf-8")
    return {"kept": allowed, "removed": removed}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--site", type=Path, required=True)
    args = parser.parse_args()
    result = sync_published_figures(ROOT, args.site)
    print(json.dumps({"kept": len(result["kept"]), "removed": len(result["removed"])}, indent=2))
